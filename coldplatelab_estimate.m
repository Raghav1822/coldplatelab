function result = coldplatelab_estimate(design, flowLpm, coolantDensity, pumpEfficiency)
%COLDPLATELAB_ESTIMATE Estimate pressure drop and pump input at an operating point.
% The pressure model is a reference-point scaling law, not validated CFD.
% Inputs: flowLpm (L/min), coolantDensity (kg/m^3), pumpEfficiency (0-1).

validateattributes(flowLpm, {'numeric'}, {'scalar','real','finite','positive'});
validateattributes(coolantDensity, {'numeric'}, {'scalar','real','finite','positive'});
validateattributes(pumpEfficiency, {'numeric'}, {'scalar','real','finite','>',0,'<=',1});

required = {'PressureDropKPa','ReferenceFlowLpm'};
if ~isstruct(design) || ~all(isfield(design, required))
    error('ColdPlateLab:InvalidDesign', ...
        'Design must include PressureDropKPa and ReferenceFlowLpm fields.');
end
validateattributes(design.PressureDropKPa, {'numeric'}, ...
    {'scalar','real','finite','positive'});
validateattributes(design.ReferenceFlowLpm, {'numeric'}, ...
    {'scalar','real','finite','positive'});

referenceDensity = 997;
pressureDropKPa = design.PressureDropKPa .* ...
    (flowLpm ./ design.ReferenceFlowLpm).^2 .* ...
    (coolantDensity ./ referenceDensity);
flowM3s = flowLpm ./ 60000;
hydraulicPowerW = pressureDropKPa .* 1000 .* flowM3s;

result = struct( ...
    'PressureDropKPa', pressureDropKPa, ...
    'HydraulicPowerW', hydraulicPowerW, ...
    'ElectricalInputW', hydraulicPowerW ./ pumpEfficiency, ...
    'FlowLpm', flowLpm, ...
    'CoolantDensityKgM3', coolantDensity, ...
    'PumpEfficiency', pumpEfficiency);
end
